/**
 * Parser-level PPTX coverage. A real package also carries
 * ppt/slides/slideLayouts/… and ppt/slides/slideMasters/… whose entry names
 * start with "ppt/slides/slide" — those must never become slides. The in-memory
 * edge-case deck and real repository sample cover both package parsing and
 * drawing; assets are test-only and never ship in the app APK.
 */
@RunWith(AndroidJUnit4::class)
class PptxParserTest {

    @Test
    fun opensTheRepositoryDeckThroughAFileUri() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val target = instrumentation.targetContext
        val file = File(target.cacheDir, "leaf-lite-project-deck.pptx")
        try {
            instrumentation.context.assets.open("Project-Deck.pptx").use { input ->
                file.outputStream().use { output -> input.copyTo(output) }
            }
            val slides = PptxParser {
                target.contentResolver.openInputStream(Uri.fromFile(file))
            }.parse()

            assertEquals("the real three-slide deck must open", 3, slides.size)
            val text = slides.flatMap { slide ->
                slide.shapes.flatMap { shape ->
                    (shape as? PptxParser.Shape.TextBox)?.paragraphs.orEmpty()
                        .flatMap { paragraph -> paragraph.runs.map { it.text } }
                }
            }.joinToString(" ")
            assertTrue(text.contains("Leaf Lite Deck"))
            assertTrue(text.contains("What this proves"))
            assertTrue(text.contains("Generated by tools/make_samples.py"))

            // Opening is not enough if every glyph is accidentally scaled by
            // px-per-EMU instead of converting OOXML points first. Render the
            // real first slide and assert it contains visible ink.
            val width = 360
            val height = (width * slides.first().heightEmu / slides.first().widthEmu).toInt()
            val view = SlideView(target).apply { slide = slides.first() }
            view.measure(
                View.MeasureSpec.makeMeasureSpec(width, View.MeasureSpec.EXACTLY),
                View.MeasureSpec.makeMeasureSpec(height, View.MeasureSpec.EXACTLY)
            )
            view.layout(0, 0, width, height)
            val bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
            try {
                view.draw(Canvas(bitmap))
                var inkPixels = 0
                for (y in 4 until height - 4) {
                    for (x in 4 until width - 4) {
                        if (bitmap.getPixel(x, y) != Color.WHITE) inkPixels++
                    }
                }
                assertTrue("slide text must render visibly; found $inkPixels ink pixels", inkPixels > 20)
            } finally {
                bitmap.recycle()
            }

            val intent = Intent(target, ViewerActivity::class.java).apply {
                data = Uri.fromFile(file)
                putExtra(ViewerActivity.EXTRA_NAME, file.name)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            val viewer = instrumentation.startActivitySync(intent) as ViewerActivity
            try {
                val deadline = System.currentTimeMillis() + 5_000
                var displayedSlides = 0
                while (System.currentTimeMillis() < deadline && displayedSlides != 3) {
                    instrumentation.waitForIdleSync()
                    instrumentation.runOnMainSync {
                        displayedSlides = viewer.findViewById<LinearLayout>(R.id.contentHolder)
                            .childCount
                    }
                    if (displayedSlides != 3) Thread.sleep(80)
                }
                assertEquals("ViewerActivity must render all three slides", 3, displayedSlides)
            } finally {
                instrumentation.runOnMainSync { viewer.finish() }
            }
        } finally {
            file.delete()
        }
    }

    @Test
    fun parseIgnoresLayoutsAndMastersAndReadsRealSlides() {
        val deck = deckBytes()
        val slides = PptxParser { ByteArrayInputStream(deck) }.parse()

        assertEquals("layouts/masters must not become slides", 2, slides.size)
        assertEquals(12192000f, slides[0].widthEmu, 0.5f)
        assertEquals(6858000f, slides[0].heightEmu, 0.5f)

        val allText = slides.flatMap { slide ->
            slide.shapes.flatMap { shape ->
                (shape as? PptxParser.Shape.TextBox)?.paragraphs.orEmpty()
                    .flatMap { para -> para.runs.map { it.text } }
            }
        }
        assertEquals(listOf("First", "Bulleted", "Second"), allText)
        assertFalse(allText.any { it.contains("LAYOUT") })
        assertFalse(allText.any { it.contains("MASTER") })

        val first = slides[0].shapes
            .filterIsInstance<PptxParser.Shape.TextBox>()
            .flatMap { it.paragraphs }
        assertTrue(first.any { it.bullet && it.runs.any { run -> run.text == "Bulleted" } })
        assertTrue(first.any { para -> !para.bullet && para.runs.any { it.text == "First" } })
    }

    // ------------------------------------------------------------- fixtures

    private fun deckBytes(): ByteArray {
        val out = ByteArrayOutputStream()
        ZipOutputStream(out).use { zip ->
            fun put(name: String, xml: String) {
                zip.putNextEntry(ZipEntry(name))
                zip.write(xml.toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }
            // Entries deliberately in non-slide order to exercise the sort.
            put("ppt/slides/slideLayouts/slideLayout1.xml", slideLike("LAYOUT", bulletFirst = false))
            put("ppt/slides/slideMasters/slideMaster1.xml", slideLike("MASTER", bulletFirst = false))
            put("ppt/slides/slide2.xml", slideLike("Second", bulletFirst = false))
            put("ppt/slides/slide1.xml", slideLike("First", bulletFirst = true))
            put(
                "ppt/presentation.xml",
                """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
                   <p:presentation xmlns:a="$NS_A" xmlns:r="$NS_R" xmlns:p="$NS_P">
                     <p:sldMasterIdLst/>
                     <p:sldIdLst/>
                     <p:sldSz cx="12192000" cy="6858000"/>
                   </p:presentation>"""
            )
        }
        return out.toByteArray()
    }

    private fun slideLike(title: String, bulletFirst: Boolean): String {
        val bulletPara = if (bulletFirst) {
            """
            <a:p><a:pPr><a:buChar char="&#8226;"/></a:pPr>
              <a:r><a:rPr lang="en-US"/><a:t>Bulleted</a:t></a:r>
            </a:p>
            """
        } else {
            ""
        }
        return """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
          <p:sld xmlns:a="$NS_A" xmlns:r="$NS_R" xmlns:p="$NS_P">
            <p:cSld>
              <p:spTree>
                <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
                <p:grpSpPr/>
                <p:sp>
                  <p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>
                  <p:spPr>
                    <a:xfrm><a:off x="838200" y="228600"/><a:ext cx="8382000" cy="1143000"/></a:xfrm>
                    <a:prstGeom prst="rect"><a:avLst/></a:prstGeom>
                  </p:spPr>
                  <p:txBody>
                    <a:bodyPr/>
                    <a:lstStyle/>
                    <a:p>
                      <a:r><a:rPr lang="en-US" sz="3600" b="1"/><a:t>$title</a:t></a:r>
                    </a:p>
                    $bulletPara
                  </p:txBody>
                </p:sp>
              </p:spTree>
            </p:cSld>
          </p:sld>"""
    }

    private companion object {
        const val NS_A = "http://schemas.openxmlformats.org/drawingml/2006/main"
        const val NS_R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
        const val NS_P = "http://schemas.openxmlformats.org/presentationml/2006/main"
    }
}
