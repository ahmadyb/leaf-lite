def para(text: str, style: str | None = None, bold: bool = False, italic: bool = False,
         underline: bool = False, size: int | None = None, list_id: str | None = None,
         level: int = 0) -> str:
    props = []
    if style:
        props.append(f'<w:pStyle w:val="{style}"/>')
    if list_id:
        props.append(f'<w:numPr><w:ilvl w:val="{level}"/><w:numId w:val="{list_id}"/></w:numPr>')
    ppr = f"<w:pPr>{''.join(props)}</w:pPr>" if props else ""
    rpr = "<w:rPr>" + ("<w:b/>" if bold else "") + ("<w:i/>" if italic else "") + \
          ("<w:u w:val=\"single\"/>" if underline else "") + \
          (f'<w:sz w:val="{size * 2}"/>' if size else "") + "</w:rPr>"
    return f'<w:p>{ppr}<w:r>{rpr}<w:t xml:space="preserve">{text}</w:t></w:r></w:p>'


