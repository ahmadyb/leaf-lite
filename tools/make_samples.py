def make_image() -> bytes:
    from PIL import Image, ImageDraw

    size = 256
    image = Image.new("RGB", (size, size), "#E4F5EB")
    draw = ImageDraw.Draw(image)
    for y in range(size):
        blend = y / (size - 1)
        colour = (
            int(0x26 + (0x12 - 0x26) * blend),
            int(0xB6 + (0x86 - 0xB6) * blend),
            int(0x72 + (0x4F - 0x72) * blend),
        )
        draw.line([(0, y), (size, y)], fill=colour)
    # a chunky leaf: two arcs meeting at the tips
    draw.polygon([(128, 30), (210, 120), (128, 226), (46, 120)], outline="#FFFFFF")
    draw.line([(128, 30), (128, 226)], fill="#FFFFFF", width=6)
    draw.arc([46, 70, 210, 226], start=200, end=340, fill="#FFFFFF", width=6)
    draw.arc([46, 70, 210, 226], start=20, end=160, fill="#FFFFFF", width=6)

    import io

    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    )


PPTX_NS = (
    'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
    'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
    'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"'
)


def pptx_shape(shape_id: int, name: str, x: int, y: int, w: int, h: int, body: str) -> str:
    return (
        f'<p:sp><p:nvSpPr><p:cNvPr id="{shape_id}" name="{name}"/>'
        f'<p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>'
        f'<p:spPr><a:xfrm><a:off x="{x}" y="{y}"/><a:ext cx="{w}" cy="{h}"/></a:xfrm>'
        f'<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>'
        f'<p:txBody><a:bodyPr/><a:lstStyle/>{body}</p:txBody></p:sp>'
    )


def pptx_para(text: str, size: int = 1800, bold: bool = False, italic: bool = False,
              color: str | None = None, bullet: bool = False, align: str = "l") -> str:
    rpr = f'<a:rPr lang="en-US" sz="{size}"'
    if bold:
        rpr += ' b="1"'
    if italic:
        rpr += ' i="1"'
    rpr += ">"
    if color:
        rpr += f'<a:solidFill><a:srgbClr val="{color}"/></a:solidFill>'
    rpr += "</a:rPr>"
    ppr = f'<a:pPr algn="{align}"'
    ppr += ">" if bullet else '/>'
    if bullet:
        ppr += '<a:buFont typeface="Arial"/><a:buChar char="•"/></a:pPr>'
    return (
        f'<a:p>{ppr}<a:r>{rpr}<a:t>{xml_escape(text)}</a:t></a:r></a:p>'
    )


