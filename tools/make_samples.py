def col(index: int) -> str:
    name = ""
    index += 1
    while index:
        index, rem = divmod(index - 1, 26)
        name = chr(65 + rem) + name
    return name


def make_xlsx(path: Path) -> None:
    teams = ["Design", "Engineering", "Marketing", "Support", "Operations", "Finance"]
    regions = ["EMEA", "AMER", "APAC"]

    sheet_bodies = {}
    for sheet_index in range(3):
        rows = []
        rows.append(
            '<row r="1">'
            '<c r="A1" t="inlineStr"><is><t>Team</t></is></c>'
            '<c r="B1" t="inlineStr"><is><t>Region</t></is></c>'
            '<c r="C1" t="inlineStr"><is><t>Budget</t></is></c>'
            '<c r="D1" t="inlineStr"><is><t>Spent</t></is></c>'
            '<c r="E1" t="inlineStr"><is><t>Headcount</t></is></c>'
            '<c r="F1" t="inlineStr"><is><t>Review date</t></is></c>'
            '<c r="G1" t="inlineStr"><is><t>On track</t></is></c>'
            "</row>"
        )
        for r in range(42):
            row_number = r + 2
            team = teams[r % len(teams)]
            region = regions[(r + sheet_index) % len(regions)]
            budget = 4000 + r * 731 + sheet_index * 250
            spent = int(budget * (0.52 + (r % 7) / 20.0))
            headcount = 3 + (r % 9)
            serial = 45000 + r * 7 + sheet_index * 30  # ~2023-03-15 onwards
            on_track = "TRUE" if r % 3 else "FALSE"
            # shared strings (t="s") for text columns, numbers and a date column
            rows.append(
                f'<row r="{row_number}">'
                f'<c r="A{row_number}" t="s"><v>{r % len(teams)}</v></c>'
                f'<c r="B{row_number}" t="s"><v>{len(teams) + (r + sheet_index) % len(regions)}</v></c>'
                f'<c r="C{row_number}"><v>{budget}</v></c>'
                f'<c r="D{row_number}"><v>{spent}</v></c>'
                f'<c r="E{row_number}"><v>{headcount}</v></c>'
                f'<c r="F{row_number}" s="1"><v>{serial}</v></c>'
                f'<c r="G{row_number}" t="b"><v>{on_track}</v></c>'
                "</row>"
            )
        sheet_bodies[f"sheet{sheet_index + 1}"] = rows

    shared = teams + regions
    shared_strings = "".join(f"<si><t>{value}</t></si>" for value in shared)

    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(
            "[Content_Types].xml",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            + "".join(
                f'<Override PartName="/xl/worksheets/sheet{i}.xml" '
                'ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
                for i in (1, 2, 3)
            )
            + '<Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>'
            '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>'
            "</Types>",
        )
        zf.writestr(
            "_rels/.rels",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            "</Relationships>",
        )
        zf.writestr(
            "xl/workbook.xml",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            "<sheets>"
            '<sheet name="Q1" sheetId="1" r:id="rId1"/>'
            '<sheet name="Q2" sheetId="2" r:id="rId2"/>'
            '<sheet name="Q3" sheetId="3" r:id="rId3"/>'
            "</sheets></workbook>",
        )
        zf.writestr(
            "xl/_rels/workbook.xml.rels",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
            '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet2.xml"/>'
            '<Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet3.xml"/>'
            '<Relationship Id="rId4" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>'
            '<Relationship Id="rId5" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>'
            "</Relationships>",
        )
        zf.writestr(
            "xl/sharedStrings.xml",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            f'count="{len(shared)}" uniqueCount="{len(shared)}">{shared_strings}</sst>',
        )
        # style 0 = default, style 1 = built-in date format (numFmtId 14)
        zf.writestr(
            "xl/styles.xml",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
            '<numFmts count="1"><numFmt numFmtId="164" formatCode="yyyy\\-mm\\-dd"/></numFmts>'
            '<cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/>'
            '<xf numFmtId="14" fontId="0" fillId="0" borderId="0" applyNumberFormat="1"/></cellXfs>'
            "</styleSheet>",
        )
        for index in (1, 2, 3):
            zf.writestr(
                f"xl/worksheets/sheet{index}.xml",
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
                f'<sheetData>{"".join(sheet_bodies[f"sheet{index}"])}</sheetData>'
                "</worksheet>",
            )


