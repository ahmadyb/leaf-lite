def esc(text: str) -> str:
    return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def make_pdf(path: Path, pages: int = 12) -> None:
    """A small but structurally correct PDF 1.4 writer (uncompressed)."""
    width, height = 595, 842  # A4 points

    def page_content(index: int) -> bytes:
        lines = [
            "BT /F1 26 Tf 72 760 Td (Leaf Lite sample PDF) Tj ET",
            f"BT /F1 13 Tf 72 730 Td ({esc('Q3 Performance Report - page %d of %d' % (index + 1, pages))}) Tj ET",
            "0.243 0.643 0.388 rg 72 470 60 %d re f" % (40 + index * 18),
            "0.290 0.796 0.514 rg 148 470 60 %d re f" % (70 + (index % 5) * 22),
            "0.071 0.525 0.310 rg 224 470 60 %d re f" % (30 + (index % 4) * 30),
            "BT /F1 11 Tf 72 440 Td "
            f"({esc('Revenue grew %.1f%% against plan in region %d.' % (2.4 + index, index + 1))}) Tj ET",
            "BT /F1 11 Tf 72 420 Td (Leaf Lite renders this page with the built-in Android PDF renderer.) Tj ET",
            "0.898 0.933 0.918 RG 1 w 72 380 451 1 re S",
            "BT /F1 10 Tf 72 360 Td (Generated by tools/make_samples.py) Tj ET",
        ]
        return "\n".join(lines).encode("cp1252", errors="replace")

    objects: list[bytes] = []
    # 1: catalog
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    # 2: pages tree
    kids = " ".join(f"{3 + i} 0 R" for i in range(pages))
    objects.append(f"<< /Type /Pages /Kids [{kids}] /Count {pages} >>".encode())
    # 3 .. 2+pages: page objects
    font_obj = 3 + pages
    for i in range(pages):
        content_obj = font_obj + 1 + i
        objects.append(
            (
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {width} {height}] "
                f"/Resources << /Font << /F1 {font_obj} 0 R >> >> "
                f"/Contents {content_obj} 0 R >>"
            ).encode()
        )
    # font
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    # content streams
    for i in range(pages):
        data = page_content(i)
        objects.append(
            b"<< /Length " + str(len(data)).encode() + b" >>\nstream\n" + data + b"\nendstream"
        )

    out = bytearray()
    out += b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode() + body + b"\nendobj\n"

    xref_offset = len(out)
    count = len(objects) + 1
    out += f"xref\n0 {count}\n".encode()
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {count} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n".encode()
    path.write_bytes(bytes(out))


